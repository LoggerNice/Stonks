function createActivity(id, name, baseCost, baseIncomePerSecond) {
  return {
    id,
    name,
    baseCost,
    baseIncomePerSecond,
    level: 0,
  };
}

function makeHistory(price, volatility, points = 3600) {
  const history = [price];
  let current = price;

  for (let i = 1; i < points; i += 1) {
    current = current / (1 + (Math.random() - 0.5) * volatility * 2);
    history.unshift(current);
  }

  return history;
}

